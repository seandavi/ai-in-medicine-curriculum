"""Extract the narration script from a deck's speaker notes.

The speaker notes in each deck are written to be read aloud. Two kinds of
paragraph are marked:

- "LIVE: ..." is a cue for a presenter running the live Zoom session. It stays
  in the speaker view and is left out of the narration script.
- "PAUSE: N min. ..." is for the recorded version: the narrator reads the rest
  of the paragraph, and the learner then stops for about N minutes. A live
  presenter skips it.

    python3 slides/narration.py slides/core-foundations.qmd

writes slides/core-foundations-narration.md: one section per slide, numbered as
in the deck, with a word count, a spoken-time estimate at 150 words a minute,
and the pauses. Run it again after editing any notes.
"""

import re
import sys
from pathlib import Path

WORDS_PER_MINUTE = 150
PAUSE = re.compile(r"^PAUSE:\s*(\d+)\s*min\.?\s*(.*)$")


def slides(qmd: str):
    """Yield (title, notes paragraphs) for each slide after the title slide."""
    title, notes, in_code, in_notes, buf = None, [], False, False, []
    for line in qmd.splitlines():
        if line.startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            continue
        if in_notes:
            if line.strip() == ":::":
                in_notes = False
                notes = [p.strip().replace("\n", " ") for p in "\n".join(buf).split("\n\n") if p.strip()]
                buf = []
            else:
                buf.append(line)
            continue
        if line.strip() in ("::: notes", "::: {.notes}"):
            in_notes = True
            continue
        heading = re.match(r"^#{1,2}( |$)(.*)", line)
        if heading:
            if title is not None:
                yield title, notes
            text = heading.group(2)
            menu = re.search(r'data-menu-title="([^"]+)"', text)
            title = re.sub(r"\s*\{.*\}\s*$", "", text).strip() or (menu.group(1) if menu else "(untitled)")
            notes = []
    if title is not None:
        yield title, notes


def main(path: str) -> None:
    src = Path(path)
    body, total_words, total_pause = [], 0, 0
    for number, (title, notes) in enumerate(slides(src.read_text(encoding="utf-8")), start=2):
        spoken, pauses = [], 0
        for p in notes:
            if p.startswith("LIVE:"):
                continue
            pause = PAUSE.match(p)
            if pause:
                pauses += int(pause.group(1))
                spoken.append(f"**[Pause, about {pause.group(1)} min.]** {pause.group(2)}")
            else:
                spoken.append(p)
        words = sum(len(re.sub(r"\*\*\[.*?\]\*\*", "", p).split()) for p in spoken)
        total_words += words
        total_pause += pauses
        seconds = round(words / WORDS_PER_MINUTE * 60)
        meta = f"*{words} words, about {seconds} s of speech" + (f", then {pauses} min paused*" if pauses else "*")
        body += [f"## {number}. {title}", "", meta, ""]
        body += [p + "\n" for p in spoken] or ["*(no narration)*\n"]
    speech = total_words / WORDS_PER_MINUTE
    header = [
        f"# Narration script: {src.stem}",
        "",
        f"Generated by `slides/narration.py` from the speaker notes in `{src.name}`.",
        "Do not edit this file; edit the notes and run the script again.",
        "Slide numbers match the deck. Slide 1 is the title slide and has no narration.",
        "If a synthetic voice reads this script, say so at the start of the recording.",
        "",
        f"Total: {total_words} words, about {speech:.0f} minutes of speech, plus about "
        f"{total_pause} minutes of pauses for the activities: about {speech + total_pause:.0f} minutes on your own.",
        "",
    ]
    out = src.with_name(f"{src.stem}-narration.md")
    out.write_text("\n".join(header + body).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {out} ({total_words} words, {speech:.0f} min speech + {total_pause} min pauses)")


if __name__ == "__main__":
    main(sys.argv[1])
